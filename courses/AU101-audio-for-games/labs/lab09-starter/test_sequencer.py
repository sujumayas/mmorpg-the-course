import unittest

import sequencer as S

T = {
    ("explore", "combat"): "bar",
    ("explore", "boss"): "beat",
    ("combat", "explore"): "phrase",
}


class TestSync(unittest.TestCase):
    def test_lengths(self):
        self.assertAlmostEqual(S.unit_seconds("beat"), 0.5)
        self.assertAlmostEqual(S.unit_seconds("bar"), 2.0)
        self.assertAlmostEqual(S.unit_seconds("phrase"), 8.0)
        self.assertAlmostEqual(S.unit_seconds("bar", bpm=90), 8 / 3)

    def test_next_sync(self):
        self.assertAlmostEqual(S.next_sync(0.1, "bar"), 2.0)
        self.assertAlmostEqual(S.next_sync(2.0, "bar"), 2.0)
        self.assertAlmostEqual(S.next_sync(2.01, "beat"), 2.5)
        self.assertAlmostEqual(S.next_sync(9.0, "phrase"), 16.0)
        self.assertAlmostEqual(S.next_sync(1.0, "bar", bpm=90), 8 / 3)
        self.assertAlmostEqual(S.next_sync(3.7, "immediate"), 3.7)

    def test_float_boundary(self):
        # 0.1 * 30 is 3.0000000000000004 in floating point; still the beat at 3.0
        self.assertAlmostEqual(S.next_sync(0.1 * 30, "beat"), 3.0)

    def test_expected_wait(self):
        self.assertAlmostEqual(S.expected_wait("bar"), 1.0)
        self.assertAlmostEqual(S.expected_wait("phrase", bpm=60), 8.0)


class TestDirector(unittest.TestCase):
    def test_simple_switch(self):
        log = S.run([(3.3, "state", "combat")], transitions=T)
        self.assertEqual(log, [(4.0, "switch", "explore", "combat")])

    def test_cancel(self):
        log = S.run([(3.3, "state", "combat"), (3.8, "state", "explore")], transitions=T)
        self.assertEqual(log, [])

    def test_last_request_wins(self):
        log = S.run([(1.0, "state", "combat"), (1.2, "state", "boss")], transitions=T)
        self.assertEqual(log, [(1.5, "switch", "explore", "boss")])

    def test_uses_current_state(self):
        log = S.run([(0.4, "state", "combat"), (9.0, "state", "explore")], transitions=T)
        self.assertEqual(log, [(2.0, "switch", "explore", "combat"),
                               (16.0, "switch", "combat", "explore")])

    def test_default_unit(self):
        log = S.run([(0.3, "state", "victory")], transitions=T)
        self.assertEqual(log, [(2.0, "switch", "explore", "victory")])

    def test_stinger_on_beat(self):
        log = S.run([(3.3, "stinger", "spotted"), (3.3, "state", "combat")], transitions=T)
        self.assertIn((3.5, "stinger", "spotted"), log)
        self.assertIn((4.0, "switch", "explore", "combat"), log)
        self.assertEqual(log[0][1], "stinger")


if __name__ == "__main__":
    unittest.main()
