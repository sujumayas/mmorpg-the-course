import math
import os
import tempfile
import unittest
import wave

import layers as L


class TestStemGain(unittest.TestCase):
    def test_bed(self):
        self.assertEqual(L.stem_gain(0.0, None, None), 1.0)
        self.assertEqual(L.stem_gain(1.0, None, None), 1.0)

    def test_ramp(self):
        self.assertAlmostEqual(L.stem_gain(0.1, 0.2, 0.2), 0.0)
        self.assertAlmostEqual(L.stem_gain(0.3, 0.2, 0.2), 0.5)
        self.assertAlmostEqual(L.stem_gain(0.4, 0.2, 0.2), 1.0)
        self.assertAlmostEqual(L.stem_gain(0.95, 0.2, 0.2), 1.0)
        self.assertAlmostEqual(L.stem_gain(0.6, 0.45, 0.2), 0.75)


class TestLevel(unittest.TestCase):
    def test_one_stem(self):
        self.assertAlmostEqual(L.level_db([1, 0, 0, 0]), 0.0)

    def test_four_stems(self):
        self.assertAlmostEqual(L.level_db([1, 1, 1, 1]), 6.0206, places=3)

    def test_partial(self):
        self.assertAlmostEqual(L.level_db([1, 1, 0.25, 0]), 3.1439, places=3)

    def test_silence(self):
        self.assertEqual(L.level_db([0, 0]), float("-inf"))


class TestSmooth(unittest.TestCase):
    def test_rise_limited(self):
        self.assertAlmostEqual(L.smooth(0.0, 1.0, 0.5, 0.1, 0.1), 0.05)

    def test_fall_limited(self):
        self.assertAlmostEqual(L.smooth(1.0, 0.0, 0.5, 0.1, 0.1), 0.99)

    def test_no_overshoot(self):
        self.assertAlmostEqual(L.smooth(0.48, 0.5, 0.5, 0.1, 0.1), 0.5)
        self.assertAlmostEqual(L.smooth(0.505, 0.5, 0.5, 0.1, 0.1), 0.5)

    def test_time_to_full(self):
        x, steps = 0.0, 0
        while x < 1.0:
            x = L.smooth(x, 1.0, 0.5, 0.1, 0.25)
            steps += 1
        self.assertEqual(steps, 8)  # 0.125 per step, exact in binary


class TestEqualPower(unittest.TestCase):
    def test_midpoint(self):
        self.assertAlmostEqual(L.equal_power(0.5) ** 2 + L.equal_power(0.5) ** 2, 1.0)


class TestRender(unittest.TestCase):
    def test_short_render(self):
        path = os.path.join(tempfile.mkdtemp(), "t.wav")
        peak = L.render(lambda t: 1.0, 0.5, path, sr=8000)
        with wave.open(path) as f:
            self.assertEqual(f.getnframes(), 4000)
        self.assertTrue(0.05 < peak <= 1.0)


if __name__ == "__main__":
    unittest.main()
