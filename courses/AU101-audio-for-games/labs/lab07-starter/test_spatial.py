import math
import unittest

import spatial as s


class TestDecibels(unittest.TestCase):
    def test_to_db(self):
        self.assertAlmostEqual(s.to_db(1.0), 0.0, places=6)
        self.assertAlmostEqual(s.to_db(0.5), -6.0206, places=3)
        self.assertAlmostEqual(s.to_db(0.1), -20.0, places=6)
        self.assertEqual(s.to_db(0.0), float("-inf"))


class TestCurves(unittest.TestCase):
    def test_inverse(self):
        self.assertAlmostEqual(s.inverse_gain(0.5, 1), 1.0)
        self.assertAlmostEqual(s.inverse_gain(4, 1), 0.25)
        self.assertAlmostEqual(s.inverse_gain(4, 2), 0.5)
        self.assertAlmostEqual(s.inverse_gain(3, 1, rolloff=2), 0.2)

    def test_linear(self):
        self.assertAlmostEqual(s.linear_gain(0.5, 1, 32), 1.0)
        self.assertAlmostEqual(s.linear_gain(16.5, 1, 32), 0.5)
        self.assertAlmostEqual(s.linear_gain(32, 1, 32), 0.0)
        self.assertAlmostEqual(s.linear_gain(100, 1, 32), 0.0)
        self.assertAlmostEqual(s.linear_gain(16.5, 1, 32, rolloff=2), 0.0)

    def test_tapered(self):
        # near: inverse is smaller; far: squared linear is smaller
        self.assertAlmostEqual(s.tapered_gain(2, 1, 32), 0.5)
        self.assertAlmostEqual(s.tapered_gain(28, 1, 32), (4 / 31) ** 2)
        self.assertAlmostEqual(s.tapered_gain(24, 1, 32), 1 / 24)
        self.assertAlmostEqual(s.tapered_gain(32, 1, 32), 0.0)
        self.assertAlmostEqual(s.tapered_gain(0.2, 1, 32), 1.0)


class TestRadius(unittest.TestCase):
    def test_inverse_radius(self):
        r = s.audible_radius(lambda d: s.inverse_gain(d, 1), -20)
        self.assertAlmostEqual(r, 10.0, delta=0.01)
        r = s.audible_radius(lambda d: s.inverse_gain(d, 2), -40)
        self.assertAlmostEqual(r, 200.0, delta=0.01)

    def test_linear_radius(self):
        r = s.audible_radius(lambda d: s.linear_gain(d, 1, 32), -6.0206)
        self.assertAlmostEqual(r, 16.5, delta=0.01)

    def test_never_quiet(self):
        self.assertEqual(s.audible_radius(lambda d: 1.0, -20), math.inf)


class TestPan(unittest.TestCase):
    def test_centre_is_minus_3db(self):
        left, right = s.pan_gains((0, 0), (1, 0), (0, 10))
        self.assertAlmostEqual(left, right)
        self.assertAlmostEqual(s.to_db(left), -3.0103, places=3)

    def test_hard_right_and_left(self):
        left, right = s.pan_gains((0, 0), (1, 0), (5, 0))
        self.assertAlmostEqual(left, 0.0, places=9)
        self.assertAlmostEqual(right, 1.0)
        left, right = s.pan_gains((2, 2), (1, 0), (-8, 2))
        self.assertAlmostEqual(left, 1.0)
        self.assertAlmostEqual(right, 0.0, places=9)

    def test_power_constant(self):
        for src in [(3, 4), (-1, 7), (6, -2), (0, -5)]:
            left, right = s.pan_gains((0, 0), (0, -2), src)
            self.assertAlmostEqual(left ** 2 + right ** 2, 1.0)

    def test_rotated_listener(self):
        # listener faces +x, so its right-hand side is -y
        left, right = s.pan_gains((0, 0), (0, -1), (0, -3))
        self.assertAlmostEqual(right, 1.0)

    def test_front_back_same(self):
        front = s.pan_gains((0, 0), (1, 0), (3, 4))
        back = s.pan_gains((0, 0), (1, 0), (3, -4))
        self.assertAlmostEqual(front[0], back[0])
        self.assertAlmostEqual(front[1], back[1])

    def test_on_listener(self):
        left, right = s.pan_gains((1, 1), (1, 0), (1, 1))
        self.assertAlmostEqual(left, right)


if __name__ == "__main__":
    unittest.main()
