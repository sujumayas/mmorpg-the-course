"""PR101 Lab 02: build the practice repository.

Usage:
    python setup_lab02.py            # creates ./lab02-repo
    python setup_lab02.py --force    # deletes and recreates it

Needs Git 2.28 or later on PATH. Standard-library Python 3.10+.
The repository it builds:
  main          README, DECISIONS.md, game/*.cfg, and a committed cache folder
  feature/hud   changes game/hud.cfg only (merges cleanly)
  balance-pass  changes game/enemy.cfg; main has also changed the same line
"""
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path("lab02-repo")
BOT = {
    "GIT_AUTHOR_NAME": "Setup Bot", "GIT_AUTHOR_EMAIL": "setup@lab02.invalid",
    "GIT_COMMITTER_NAME": "Setup Bot", "GIT_COMMITTER_EMAIL": "setup@lab02.invalid",
}


def git(*args, date="2026-01-12T10:00:00"):
    env = dict(os.environ, **BOT, GIT_AUTHOR_DATE=date, GIT_COMMITTER_DATE=date)
    subprocess.run(["git", *args], cwd=REPO, env=env, check=True,
                   stdout=subprocess.DEVNULL)


def write(path, text):
    p = REPO / path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


def main():
    if REPO.exists():
        if "--force" not in sys.argv:
            sys.exit(f"{REPO} already exists. Use --force to recreate it.")
        shutil.rmtree(REPO)
    REPO.mkdir()
    git("init", "-q", "-b", "main")

    write("README.md", "# Slime Hop\n\nA one-screen jam platformer. Lab 02 practice repo.\n")
    write("DECISIONS.md",
          "# Design decisions\n\n"
          "- 2026-01-12: player speed stays at 200 until the next playtest.\n")
    write("game/player.cfg", "speed = 200\ngravity = 980\n\nfriction = 0.8\n\njump = 400\n")
    write("game/enemy.cfg", "[slime]\nhp = 40\n\nspeed = 60\n\ndamage = 10\n")
    write("game/hud.cfg", "scale = 1.0\nfont = mono\n")
    write(".godot/imported/cache.bin", "cached import data, regenerated by the editor\n")
    git("add", "-A")
    git("commit", "-q", "-m", "Add first playable config and README")

    git("switch", "-q", "-c", "feature/hud", date="2026-01-13T10:00:00")
    write("game/hud.cfg", "scale = 1.5\nfont = mono\n")
    git("commit", "-q", "-am", "Enlarge HUD for couch play", date="2026-01-13T10:00:00")

    git("switch", "-q", "main", date="2026-01-13T11:00:00")
    git("switch", "-q", "-c", "balance-pass", date="2026-01-13T11:00:00")
    write("game/enemy.cfg", "[slime]\nhp = 80\n\nspeed = 60\n\ndamage = 12\n")
    git("commit", "-q", "-am", "Make slimes tougher and hit harder", date="2026-01-13T12:00:00")

    git("switch", "-q", "main", date="2026-01-14T09:00:00")
    write("game/enemy.cfg", "[slime]\nhp = 50\n\nspeed = 60\n\ndamage = 10\n")
    git("commit", "-q", "-am", "Raise slime hp slightly after playtest", date="2026-01-14T09:00:00")
    write("DECISIONS.md",
          "# Design decisions\n\n"
          "- 2026-01-12: player speed stays at 200 until the next playtest.\n"
          "- 2026-01-14: slime hp is 65. Damage follows the balance pass.\n")
    git("commit", "-q", "-am", "Record slime hp decision", date="2026-01-14T09:30:00")
    print(f"Created {REPO}/ with branches main, feature/hud, balance-pass.")


if __name__ == "__main__":
    main()
