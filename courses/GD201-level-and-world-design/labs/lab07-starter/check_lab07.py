import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else HERE / "vertical_nav.py"
sys.path.insert(0, str(HERE))
spec = importlib.util.spec_from_file_location("student", TARGET)
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
from levels import CLIFF_RUIN, QUARRY, QUARRY_CANDIDATES  # noqa: E402


def close(a, b, tol=0.01):
    return a is not None and b is not None and abs(a - b) <= tol


def sorted_edges(es):
    return sorted((a, b, round(t, 3)) for a, b, t in es)


H = {"A": 10, "B": 4, "C": 10}


def c1():
    return close(m.drop_time(6), 0.775) and m.drop_time(12) is None and close(m.drop_time(12, h_safe=12), 1.095)


def c2():
    return close(m.climb_time(12), 8.0) and close(m.climb_time(6, v_climb=3), 2.0)


def c3():
    return (sorted_edges(m.edge_times(("run", "A", "C", 30), H)) == [("A", "C", 5.0), ("C", "A", 5.0)]
            and sorted_edges(m.edge_times(("slope", "B", "A", 40), H)) == [("A", "B", 6.667), ("B", "A", 10.0)])


def c4():
    return (sorted_edges(m.edge_times(("drop", "B", "A"), H)) == [("A", "B", 0.775)]
            and m.edge_times(("drop", "A", "B"), H, h_safe=5) == []
            and sorted_edges(m.edge_times(("ladder", "A", "B"), H)) == [("A", "B", 2.0), ("B", "A", 4.0)])


def c5():
    g = m.build_graph(CLIFF_RUIN)
    return (set(g) == set(CLIFF_RUIN["heights"]) and all(b != "Ruin" for b, _ in g["Overlook"])
            and close(m.shortest_time(g, "Camp", "Ruin"), 6.549) and close(m.shortest_time(g, "Ruin", "Camp"), 47.5))


def c6():
    g = m.build_graph(QUARRY)
    return (close(m.shortest_time(g, "Hub", "Pit"), 5.612) and close(m.shortest_time(g, "Pit", "Hub"), 69.167)
            and m.shortest_time({"X": [], "Y": []}, "X", "Y") == float("inf"))


def c7():
    g = m.build_graph(CLIFF_RUIN)
    return close(m.return_ratio(g, "Camp", "Ruin"), 7.253) and close(m.return_ratio(g, "Camp", "Overlook"), 1.0)


def c8():
    got = m.stranded(QUARRY, "Hub")
    want = [("Pit", 12.33), ("Sump", 10.60), ("Crusher", 5.53), ("Shelf", 3.14), ("Road", 2.02)]
    return [p for p, _ in got] == [p for p, _ in want] and all(close(r, w) for (_, r), (_, w) in zip(got, want))


def c9():
    return [p for p, _ in m.stranded(QUARRY, "Hub", limit=5.0)] == ["Pit", "Sump", "Crusher"]


def c10():
    cand, worst = m.best_shortcut(QUARRY, "Hub", QUARRY_CANDIDATES)
    return tuple(cand) == ("ladder", "Sump", "Scaffold") and close(worst, 3.24)


CHECKS = [("drop_time", c1), ("climb_time", c2), ("edge_times run and slope", c3),
          ("edge_times drop and ladder", c4), ("build_graph + shortest on Cliff Ruin", c5),
          ("shortest_time on Quarry", c6), ("return_ratio", c7), ("stranded, limit 2", c8),
          ("stranded, limit 5", c9), ("best_shortcut", c10)]


def main():
    passed = 0
    for name, fn in CHECKS:
        try:
            ok = bool(fn())
        except NotImplementedError:
            ok = False
            name += " (not implemented)"
        except Exception as e:  # show the student what broke
            ok = False
            name += f" ({type(e).__name__}: {e})"
        print(f"{'PASS' if ok else 'FAIL'}  {name}")
        passed += ok
    print(f"{passed}/{len(CHECKS)} checks pass")
    sys.exit(0 if passed == len(CHECKS) else 1)


if __name__ == "__main__":
    main()
