"""Checker for GD201 Lab 08. Run from this folder:  python check_lab08.py [your_file.py]
Do not edit this file."""
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else HERE / "story_reliability.py"
spec = importlib.util.spec_from_file_location("student", TARGET)
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
LOG = HERE / "watchtower_playtest.csv"


def close(a, b, tol=1e-3):
    return a is not None and abs(a - b) <= tol


def c1():
    return close(m.p_all([0.8, 0.5, 0.25]), 0.1) and close(m.p_all([]), 1.0)


def c2():
    return close(m.p_any([0.8, 0.5, 0.25]), 0.925) and close(m.p_any([]), 0.0)


def c3():
    ps = [0.8, 0.5, 0.5, 0.25]
    want = [1.0, 0.9625, 0.725, 0.3125, 0.05, 0.0]
    return all(close(m.p_at_least(ps, k), w) for k, w in enumerate(want))


def c4():
    return close(m.p_at_least([0.5] * 4, 2), 0.6875) and close(m.p_at_least([0.6] * 3, 2), 0.648)


def c5():
    rows = m.load_log(LOG)
    return len(rows) == 24 and rows[0]["well"] == 1 and rows[6]["well"] == 0 and sum(r["said_beat"] for r in rows) == 21


def c6():
    rows = m.load_log(LOG)
    return (close(m.estimate_p(rows, "well"), 23 / 24) and close(m.estimate_p(rows, "order"), 7 / 24)
            and close(m.estimate_p(rows, "bags"), 17 / 24))


def c7():
    rows = m.load_log(LOG)
    clues = ["well", "sickbay", "order", "bags"]
    return (close(m.observed_rate(rows, clues, 2), 20 / 24) and close(m.observed_rate(rows, clues, 4), 4 / 24)
            and close(m.observed_rate(rows, ["order"], 1), 7 / 24))


def c8():
    names, rate = m.plan_clues(m.CHAPEL_SLOTS, 1, 0.9)
    return names == ["door_lever"] and close(rate, 0.95)


def c9():
    names, rate = m.plan_clues(m.CHAPEL_SLOTS, 2, 0.9)
    return names == ["altar", "bell_rope", "door_lever", "nave_left"] and close(rate, 0.935)


def c10():
    a = m.plan_clues(m.CHAPEL_SLOTS, 3, 0.9)
    names, rate = m.plan_clues(m.CHAPEL_SLOTS, 1, 0.999)
    return (a[0] is None and names == ["altar", "bell_rope", "crypt", "door_lever", "nave_left", "nave_right"]
            and close(rate, 0.99906))


CHECKS = [("p_all", c1), ("p_any", c2), ("p_at_least, mixed clues", c3), ("p_at_least, equal clues", c4),
          ("load_log", c5), ("estimate_p", c6), ("observed_rate", c7), ("plan_clues k=1", c8),
          ("plan_clues k=2 with a tie", c9), ("plan_clues impossible and large", c10)]


def main():
    passed = 0
    for name, fn in CHECKS:
        try:
            ok = bool(fn())
        except NotImplementedError:
            ok = False
            name += " (not implemented)"
        except Exception as e:
            ok = False
            name += f" ({type(e).__name__}: {e})"
        print(f"{'PASS' if ok else 'FAIL'}  {name}")
        passed += ok
    print(f"{passed}/{len(CHECKS)} checks pass")
    sys.exit(0 if passed == len(CHECKS) else 1)


if __name__ == "__main__":
    main()
