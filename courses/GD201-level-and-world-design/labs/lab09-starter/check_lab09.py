"""Checker for GD201 Lab 09. Run from this folder:  python check_lab09.py [your_file.py]
Do not edit this file."""
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else HERE / "poi_density.py"
spec = importlib.util.spec_from_file_location("student", TARGET)
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
ZONE = HERE / "zone_marsh.csv"
SMALL = [("A", 0, 0), ("B", 100, 0), ("C", 0, 100), ("D", 300, 0)]


def close(a, b, tol=0.01):
    return a is not None and abs(a - b) <= tol


def c1():
    return (close(m.spacing_for_gap(6.4, 30), 192.0) and close(m.density_for_gap(6.4, 30), 27.126)
            and close(m.density_for_gap(5, 40), 25.0))


def c2():
    return close(m.gap_for_density(10, 25), 20.0) and close(m.gap_for_density(12.8, 6.782), 30.0)


def c3():
    z = m.load_zone(ZONE)
    return len(z) == 60 and z[0] == ("P01", 119.0, 106.0) and z[-1][0] == "P60"


def c4():
    t = m.nearest_neighbour_tour(SMALL, "A")
    want = [("A", "B", 100.0), ("B", "C", 141.421), ("C", "D", 316.228)]
    return len(t) == 3 and all(a == x and b == y and close(d, w) for (a, b, d), (x, y, w) in zip(t, want))


def c5():
    t = m.nearest_neighbour_tour(m.load_zone(ZONE), "P01")
    return (len(t) == 59 and t[0][:2] == ("P01", "P09") and close(t[0][2], 220.477)
            and close(sum(d for _, _, d in t), 14183.9, tol=0.2))


def c6():
    t = m.nearest_neighbour_tour(m.load_zone(ZONE), "P01")
    got = m.long_gaps(t, 6.4, 40)
    return [(a, b) for a, b, _ in got] == [("P11", "P05"), ("P22", "P34"), ("P39", "P46"), ("P54", "P42")] \
        and close(got[-1][2], 100.33)


def c7():
    return close(m.empty_fraction(SMALL, 150, size=400, step=100), 0.6875, tol=1e-6) \
        and close(m.empty_fraction(m.load_zone(ZONE), 250), 0.063125, tol=1e-6)


def c8():
    x, y, d = m.largest_empty_circle(SMALL, size=400, step=100)
    X, Y, D = m.largest_empty_circle(m.load_zone(ZONE))
    return (x, y) == (250, 350) and close(d, 353.553) and (X, Y) == (1325, 625) and close(D, 480.376)


def c9():
    z = m.load_zone(ZONE)
    return m.visible_count(SMALL, 0, 0, 100) == 2 and m.visible_count(z, 1375, 1625, 300) == 9 \
        and m.visible_count(z, 1375, 625, 300) == 0


CHECKS = [("spacing and density for a gap", c1), ("gap for a density", c2), ("load_zone", c3),
          ("tour on a small set, with a tie", c4), ("tour on the Marsh", c5), ("long_gaps", c6),
          ("empty_fraction", c7), ("largest_empty_circle", c8), ("visible_count", c9)]


def main():
    passed = 0
    for name, fn in CHECKS:
        try:
            ok = bool(fn())
        except NotImplementedError:
            ok = False
            name += " (not implemented)"
        except Exception as e:
            ok = False
            name += f" ({type(e).__name__}: {e})"
        print(f"{'PASS' if ok else 'FAIL'}  {name}")
        passed += ok
    print(f"{passed}/{len(CHECKS)} checks pass")
    sys.exit(0 if passed == len(CHECKS) else 1)


if __name__ == "__main__":
    main()
